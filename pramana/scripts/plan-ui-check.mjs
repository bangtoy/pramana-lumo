import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { writeFileSync } from 'node:fs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
page.setDefaultTimeout(15000);
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
const base = `http://localhost:${process.env.PORT || 3000}`;
const shots = '../docs/verification/screenshots';
try {
  const seed = await (await page.request.get(`${base}/api/rencana/RI-DT-UTYPE-01`)).json();
  const clone = await (await page.request.post(`${base}/api/rencana`, { data: {} })).json();
  assert.ok((await page.request.patch(`${base}/api/rencana/${clone.id}`, { data: { judul: 'UI verification plan', model_id: seed.model_id, items: seed.items } })).ok());
  await page.goto(`${base}/supervisor/agent?rencana=${clone.id}&chat=dock`, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('.t-title').count(), 1);
  assert.equal(await page.locator('.t-display').count(), 0);
  await page.locator('svg [data-comp="ban_roda"]').first().waitFor();
  await page.screenshot({ path: `${shots}/planner-dock.png` });
  await page.locator('[data-item-id="ITEM-3"] > button').click();
  await page.waitForFunction(() => !!document.querySelector('[data-comp="ban_roda"].is-focus'));
  await page.mouse.move(400, 80);
  await page.screenshot({ path: `${shots}/planner-selected.png` });
  await page.getByRole('button', { name: 'Edit Tyres & wheel nuts' }).click();
  await page.getByRole('textbox', { name: 'What to check', exact: true }).fill('Check the EAST QUARRY tyre pressure and wheel nuts.');
  await page.getByRole('button', { name: 'Save item', exact: true }).click();
  await page.getByText('Check the EAST QUARRY tyre pressure and wheel nuts.', { exact: true }).waitFor();
  let persisted = await (await page.request.get(`${base}/api/rencana/${clone.id}`)).json();
  assert.match(persisted.items[2].yang_dicek, /EAST QUARRY/);
  await page.getByRole('button', { name: 'Move Tyres & wheel nuts up' }).click();
  await page.waitForFunction(() => document.querySelector('[data-item-id="ITEM-3"] button span')?.textContent === '2');
  await page.getByLabel('Plan title', { exact: true }).fill('Edited through the browser');
  const titleSaved = page.waitForResponse(r => r.request().method() === 'PATCH' && r.url().includes(`/api/rencana/${clone.id}`));
  await page.getByLabel('Plan title', { exact: true }).press('Enter');
  await titleSaved;
  await page.getByRole('button', { name: 'Pin conversation', exact: true }).click();
  assert.equal(await page.getByRole('region', { name: 'Plan conversation', exact: true }).evaluate(n => n.getBoundingClientRect().width), 400);
  await page.mouse.move(400, 80);
  await page.screenshot({ path: `${shots}/planner-pinned.png` });
  await page.goto(`${base}/supervisor/agent?rencana=${clone.id}`, { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Minimise conversation', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Minimise conversation', exact: true }).click();
  await page.getByRole('textbox', { name: 'Message Lumo' }).click();
  await page.getByRole('dialog', { name: 'Lumo conversation', exact: true }).waitFor();
  await page.screenshot({ path: `${shots}/planner-dialog.png`, animations: 'disabled' });
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  await page.getByRole('button', { name: 'Add item', exact: true }).click();
  assert.equal(await page.getByLabel('Item name', { exact: true }).evaluate(n => n === document.activeElement), true);
  await page.getByLabel('Item name', { exact: true }).fill('Windscreen cleaning');
  await page.getByRole('textbox', { name: 'What to check', exact: true }).fill('Check visibility.');
  await page.getByLabel('Evidence 1 description').fill('Photo of the windscreen.');
  await page.getByRole('combobox', { name: 'Model component', exact: true }).click();
  const componentLabel = (await (await page.request.get(`${base}/api/models/${seed.model_id}`)).json()).komponen.find(component => component.comp_id === 'kabin').label;
  await page.getByRole('option', { name: componentLabel, exact: true }).click();
  await page.getByRole('button', { name: 'Save item', exact: true }).click();
  await page.getByRole('button', { name: 'Delete Windscreen cleaning', exact: true }).click();
  await page.getByRole('button', { name: 'Delete Windscreen cleaning', exact: true }).waitFor({ state: 'detached' });
  persisted = await (await page.request.get(`${base}/api/rencana/${clone.id}`)).json();
  assert.equal(persisted.items.length, 8);
  assert.equal(persisted.judul, 'Edited through the browser');
  // Complete the document upload through the actual UI and configured model.
  await page.goto(`${base}/supervisor/agent`, { waitUntil: 'networkidle' });
  await page.waitForURL(/rencana=RI-/);
  const generatedId = new URL(page.url()).searchParams.get('rencana');
  await page.getByLabel('Attach Spec Sheet', { exact: true }).setInputFiles('test/dum-trcuk-spel.webp');
  await page.getByRole('textbox', { name: 'Message Lumo' }).fill('Create a P2H plan from the Spec Sheet with required standard checks.');
  const responsePromise = page.waitForResponse(r => r.url().includes(`/api/rencana/${generatedId}/turn`), { timeout: 120000 });
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await responsePromise;
  // NDJSON can remain associated with a browser network stream after the UI
  // has consumed it. Verify the user-visible settled result, with a hard limit.
  await page.waitForFunction(() => document.querySelectorAll('[data-item-id]').length >= 8, undefined, { timeout: 120000 });
  await page.waitForFunction(() => !document.querySelector('textarea[aria-label="Message Lumo"]')?.disabled, undefined, { timeout: 120000 });
  const generated = await (await page.request.get(`${base}/api/rencana/${generatedId}`)).json();
  assert.ok(generated.spec_fakta.length > 0);
  assert.ok(generated.messages.at(-1).role === 'pramana');
  await page.screenshot({ path: `${shots}/planner-upload-result.png` });
  assert.deepEqual(errors, []);
  writeFileSync(`${shots}/plan-ui-check.json`, JSON.stringify({ clone: clone.id, generated: generatedId, count: generated.items.length, manualEdit: true, reorder: true, addDelete: true, dockPinPersistence: true, escape: true, uploadWithoutReload: true, errors }, null, 2));
  console.log('Plan UI checks passed');
} finally { await browser.close(); }
