import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const base = `http://localhost:${process.env.PORT || 3002}`;
const before = await (await fetch(base + '/api/dashboard')).json();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', e => { if (e.type() === 'error') errors.push(e.text()); });
async function snapshot(name) {
  await page.evaluate(async () => { await document.fonts.ready; await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))); });
  await page.screenshot({ path: `../docs/verification/screenshots/${name}.png`, animations: 'disabled' });
}
const panel = page.locator('#supervisor-assistant-slot');
try {
  await page.goto(`${base}/supervisor`, { waitUntil: 'networkidle' });
  await page.locator('[data-unit="DT-07"]').waitFor();
  assert.equal(await page.locator('[data-kpi="stop"] .t-metric').textContent(), String(before.kpi.stop));
  assert.equal(await page.locator('[data-kpi="inspected"] .t-metric').textContent(), `${before.kpi.unit_diperiksa}/${before.kpi.unit_total}`);
  assert.deepEqual(await page.locator('[data-unit]').evaluateAll(rows => rows.map(r => r.dataset.unit)), before.units.map(u => u.unit));
  assert.equal(await page.getByRole('link', { name: 'Summary', exact: true }).getAttribute('aria-current'), 'page');
  assert.equal(await page.locator('h1.t-display').count(), 1);
  assert.equal(await page.locator('h1.t-display').evaluate(el => getComputedStyle(el).fontSize), '22px');
  assert.equal(await page.locator('[data-kpi] .t-metric').first().evaluate(el => getComputedStyle(el).fontSize), '24px');
  assert.equal(await panel.getAttribute('data-open'), 'true');
  await snapshot('dashboard-open-1440');
  await page.getByRole('button', { name: 'Collapse Lumo panel' }).click();
  await page.waitForFunction(() => document.querySelector('#supervisor-assistant-slot').getBoundingClientRect().width === 48);
  await snapshot('dashboard-collapsed-1440');
  await page.reload({ waitUntil: 'networkidle' }); assert.equal(await panel.getAttribute('data-open'), 'false');
  const chart = page.locator('[data-trend-days]'); await chart.scrollIntoViewIfNeeded();
  const wide = await chart.boundingBox();
  await page.getByRole('button', { name: 'Expand Lumo panel' }).click();
  await page.waitForFunction(old => Number(document.querySelector('[data-trend-days]').dataset.chartWidth) < old, wide.width);
  const box = await chart.boundingBox(); assert.ok(box.width < wide.width);
  await chart.hover({ position: { x: box.width / 2, y: 100 } });
  await page.getByRole('tooltip').waitFor(); assert.match(await page.getByRole('tooltip').textContent(), /Roadworthy.*STOP/);
  assert.match(await chart.locator('[data-series="roadworthy"]').getAttribute('d'), /C/);
  assert.doesNotMatch(await chart.locator('[data-series="roadworthy"]').getAttribute('d'), /NaN|Infinity/);
  await snapshot('dashboard-chart-1440');
  await chart.focus(); await chart.press('Home');
  assert.ok((await page.getByRole('tooltip').textContent()).includes(before.tren[0].label));
  await page.getByRole('button', { name: '7 days', exact: true }).click();
  await page.locator('[data-trend-days="7"]').waitFor();
  await page.getByRole('button', { name: '14 days', exact: true }).click();
  await page.locator('[data-trend-days="14"]').waitFor();
  const liveResponse = page.waitForResponse(r => r.url().endsWith('/api/dashboard?hari=14') && r.ok());
  await page.getByRole('button', { name: 'Refresh dashboard' }).click(); await liveResponse;
  await page.waitForResponse(r => r.url().endsWith('/api/dashboard?hari=14') && r.ok(), { timeout: 14000 });
  assert.equal(await page.locator('[data-kpi="stop"]').getAttribute('href'), '/supervisor/laporan?stop=1');
  assert.match(await page.locator('[data-component="ban_roda"]').getAttribute('href'), /item=Tyres/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#supervisor-content').evaluate(el => { el.scrollTop = 0; });
  await page.waitForFunction(() => document.querySelector('aside[aria-label="Supervisor navigation"]').getBoundingClientRect().width === 64);
  await snapshot('dashboard-390');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(await page.locator('#supervisor-content').evaluate(el => el.scrollWidth <= el.clientWidth), true);
  await page.setViewportSize({ width: 1440, height: 900 });
  const tile = page.locator('[data-unit="DT-07"]');
  assert.equal(before.units.find(u => u.unit === 'DT-07').stop_tanpa_wo, true);
  const responsePromise = page.waitForResponse(r => r.url().endsWith('/api/work-order') && r.request().method() === 'POST', { timeout: 45000 });
  const started = Date.now(); await tile.getByRole('button', { name: 'Create WO', exact: true }).click();
  const response = await responsePromise; assert.equal(response.status(), 201); const created = await response.json(); assert.equal(created.length, 2);
  const creationMs = Date.now() - started;
  await tile.getByRole('button', { name: /Create WO|Creating/ }).waitFor({ state: 'detached' });
  await page.waitForFunction(expected => document.querySelector('[data-kpi="stop"] p.t-body-sm')?.textContent === `${expected} without work orders`, before.kpi.stop_tanpa_wo - 1);
  const after = await (await fetch(base + '/api/dashboard')).json();
  assert.equal(after.kpi.stop_tanpa_wo, before.kpi.stop_tanpa_wo - 1); assert.equal(after.kpi.wo_terbuka, before.kpi.wo_terbuka + 2);
  await page.getByRole('link', { name: 'Work orders', exact: true }).click();
  for (const order of created) await page.locator(`[data-work-order="${order.id}"]`).waitFor();
  assert.deepEqual(errors, []);
  const states = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await states.route('**/api/dashboard?*', route => route.fulfill({ json: { ...before, units: [], terbaru: [], komponen: [], kpi: Object.fromEntries(Object.keys(before.kpi).map(key => [key, 0])) } }));
  await states.goto(`${base}/supervisor`, { waitUntil: 'networkidle' }); await states.getByRole('heading', { name: 'No inspections yet' }).waitFor();
  await states.unroute('**/api/dashboard?*');
  await states.route('**/api/dashboard?*', route => route.fulfill({ status: 503, json: { error: 'Dashboard temporarily unavailable.' } }));
  await states.reload(); await states.getByRole('alert').filter({ hasText: 'Dashboard temporarily unavailable.' }).waitFor({ timeout: 20000 });
  await states.close();
  const result = { initialKpi: before.kpi, afterKpi: after.kpi, workOrders: created.map(w => w.id), creationMs, panelPersists: true, chartResponsive: true, chartHoverAndKeyboard: true, sevenAndFourteenDays: true, pollingAndRefresh: true, kpiLinks: true, componentLinks: true, mobileOverflowContained: true, emptyAndErrorStates: true, errors };
  writeFileSync('../docs/verification/dashboard-ui-check.json', JSON.stringify(result, null, 2)); console.log(result);
} finally { await browser.close(); }
