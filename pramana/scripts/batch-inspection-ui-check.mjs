import assert from 'node:assert/strict';
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const base = 'http://localhost:3008';
const root = process.env.SIM_ASSETS || 'D:/Orca/example file/Foto-P2H/02-Dump-Truck-Tronton-U-Type/Normal';
const files = [5, 3, 7, 4, 6].map(index => path.join(root, readdirSync(root).find(name => name.startsWith(String(index).padStart(2, '0') + '-'))));
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [], output = {};
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto(`${base}/petugas?baru=1`, { waitUntil: 'networkidle' });
  const composer = page.getByRole('textbox', { name: 'Message Lumo' });
  const turnRequest = () => page.waitForRequest(request => /\/api\/laporan\/[^/]+\/turn$/.test(new URL(request.url()).pathname) && request.method() === 'POST');
  const idle = () => page.waitForFunction(() => { const camera = document.querySelector('button[aria-label="Take a photo"]'); return camera && !camera.disabled; }, null, { timeout: 180000 });
  const send = async text => { await composer.fill(text); const request = turnRequest(); await page.getByRole('button', { name: 'Send message', exact: true }).click(); await request; await idle(); };
  await send('My name is Batch UI. I am at Riau. Let me choose my inspection plan.');
  await page.getByRole('button', { name: 'Choose inspection plan', exact: true }).click();
  const selection = turnRequest();
  await page.getByRole('option').filter({ hasText: 'P2H · U-type dump truck' }).click();
  await selection; await idle();
  const id = await page.evaluate(() => localStorage.getItem('pramana.inspection-draft'));
  output.reportId = id;
  const report = async () => (await fetch(`${base}/api/laporan/${id}`)).json();
  const overview = (await report()).messages.at(-1).inspection_checklist;
  assert.equal(overview.kind, 'overview'); assert.equal(overview.items.length, 8);
  assert.equal((await report()).unit, null, 'Checklist appears immediately after plan choice, before the unit');
  const checklist = page.locator('[data-inspection-checklist="overview"]');
  assert.equal(await checklist.locator('li').count(), 8);
  async function shot(name) { await page.evaluate(async () => { await document.fonts.ready; await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))); }); await page.screenshot({ path: `../docs/verification/screenshots/batch-inspection-${name}.png`, animations: 'disabled' }); }
  await shot('checklist-390');
  await send('Unit QA-BATCH-UI. The vehicle is parked, chocked and isolated; I inspect from a safe position with the mechanical body prop engaged where needed.');
  await page.getByRole('button', { name: 'Vehicle model', exact: true }).click();
  const gallery = page.getByLabel('Attach inspection photos', { exact: true });
  assert.notEqual(await gallery.getAttribute('multiple'), null);
  assert.equal(await gallery.getAttribute('capture'), null);
  assert.equal(await page.getByLabel('Take an inspection photo', { exact: true }).getAttribute('capture'), 'environment');
  await gallery.setInputFiles(files);
  await page.getByText(/5\/5 photos ready/).waitFor();
  assert.equal(await page.locator('[data-photo-previews] img').count(), 5);
  await shot('preview-390');
  await gallery.setInputFiles([files[0]]);
  await page.getByText('Choose up to 5 photos per message. Remove a photo before adding more.').waitFor();
  assert.equal(await page.locator('[data-photo-previews] img').count(), 5);
  await page.getByRole('button', { name: 'Remove photo 2', exact: true }).click();
  await gallery.setInputFiles([files[1]]);
  await page.getByText(/5\/5 photos ready/).waitFor();
  assert.equal(await page.getByText('Choose up to 5 photos per message. Remove a photo before adding more.').count(), 0);
  await send('All five photographed components have been checked directly: tyres and all wheel nuts on both sides intact, body welds and mounts free of structural cracks, hydraulics dry and undamaged, safety prop straight and locked, tailgate hinges and pins intact and both latches tested and locked. Only surface dirt/rust. Match photos in their supplied order to the actual components.');
  let saved = await report();
  const uploads = saved.messages.filter(message => message.role === 'user').at(-1).files;
  const sizes = await Promise.all(uploads.map(async file => (await (await fetch(`${base}/api/files/${file.id}`)).arrayBuffer()).byteLength));
  assert.equal(uploads.length, 5); assert.ok(sizes.every(size => size < 300 * 1024));
  assert.deepEqual(Object.keys(saved.hasil).sort(), ['ITEM-3', 'ITEM-4', 'ITEM-5', 'ITEM-6', 'ITEM-7']);
  assert.equal(saved.messages.filter(message => message.role === 'user').at(-1).files.length, 5);
  const update = page.locator('[data-inspection-checklist="progress"]').last();
  assert.equal(await update.locator('[data-state="recorded"]').count(), 5);
  assert.equal(await update.locator('[data-state="pending"]').count(), 3);
  assert.equal(await page.locator('[data-photo-previews]').count(), 0);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await shot('progress-390');
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(Object.keys((await report()).hasil).length, 5);
  await page.setViewportSize({ width: 1440, height: 900 });
  await shot('progress-1440');
  assert.deepEqual(errors, []);
  Object.assign(output, { checklistBeforeUnit: true, checklistItems: 8, multipleGallery: true, cameraAvailable: true, addRemoveAndLimit: true, photoSizes: sizes, findingsRecorded: 5, remaining: 3, survivedReload: true, errors });
  console.log(JSON.stringify(output));
} catch (error) { output.error = error.message; throw error; }
finally { writeFileSync('../docs/verification/batch-inspection-ui.json', JSON.stringify(output, null, 2) + '\n'); await browser.close(); }
