import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
page.setDefaultTimeout(15000);
const base = `http://localhost:${process.env.PORT || 3000}`;
const shots = process.env.PLANNER_SCREENSHOTS_DIR || join(tmpdir(), 'pramana-ui-polish');
await mkdir(shots, { recursive: true });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });

try {
  // All writes and agent calls are intercepted; the user's plans stay untouched.
  const seed = await (await page.request.get(`${base}/api/rencana/RI-DT-UTYPE-01`)).json();
  let plan = { ...seed, id: 'RI-UI-POLISH', judul: 'Dump Truck Pre-Shift Inspection', messages: [{ id: 'greeting', role: 'pramana', text: 'Upload the truck’s Spec Sheet to add supported specifications to your inspection plan.', quick_replies: ['Upload specification sheet'], created_at: seed.created_at }] };
  let history = [plan, ...Array.from({ length: 18 }, (_, index) => ({ ...seed, id: `RI-UI-HISTORY-${index}`, judul: `Inspection plan ${index + 1} · U-type dump truck` }))];
  const image = await readFile('test/dum-trcuk-spel.webp');
  const upload = { name: 'FILE-SPEC-DT.webp', mimeType: 'image/webp', buffer: image };
  const turns = [];
  await page.route('**/api/rencana**', async route => {
    const path = new URL(route.request().url()).pathname;
    if (path.endsWith('/turn')) {
      const gate = Promise.withResolvers();
      turns.push(gate);
      const fail = await gate.promise;
      if (fail) return route.fulfill({ contentType: 'application/x-ndjson', body: `${JSON.stringify({ error: 'The attachment could not be processed. Please try again.' })}\n` });
      plan = { ...plan, messages: [...plan.messages, { id: 'uploaded', role: 'user', text: '', files: [{ id: 'FILE-UI-POLISH', mime: 'image/webp' }], created_at: seed.created_at }, { id: 'reply', role: 'pramana', text: 'Reviewed the sheet and saved its supported specifications.', quick_replies: ['Review updated checklist'], created_at: seed.created_at }] };
      return route.fulfill({ contentType: 'application/x-ndjson', body: `${JSON.stringify({ status: 'Reading the attachment…' })}\n${JSON.stringify({ reply: { data: plan, messages: plan.messages } })}\n` });
    }
    if (route.request().method() === 'PATCH') {
      const body = route.request().postDataJSON();
      const id = decodeURIComponent(path.split('/').at(-1));
      if (id === plan.id) plan = { ...plan, ...body };
      history = history.map(entry => entry.id === id ? { ...entry, ...body } : entry);
      return route.fulfill({ json: id === plan.id ? plan : history.find(entry => entry.id === id) });
    }
    return route.fulfill({ json: path === '/api/rencana' ? history : plan });
  });
  await page.route('**/api/files/FILE-UI-POLISH/meta', route => route.fulfill({ json: { name: upload.name, mime: upload.mimeType } }));
  await page.route('**/api/files/FILE-UI-POLISH', route => route.fulfill({ body: image, contentType: upload.mimeType }));
  await page.addInitScript(() => {
    window.previewUrls = { created: [], revoked: [] };
    const create = URL.createObjectURL.bind(URL), revoke = URL.revokeObjectURL.bind(URL);
    URL.createObjectURL = blob => { const url = create(blob); window.previewUrls.created.push(url); return url; };
    URL.revokeObjectURL = url => { window.previewUrls.revoked.push(url); revoke(url); };
  });
  await page.goto(`${base}/supervisor/agent?rencana=${plan.id}&chat=pin`, { waitUntil: 'networkidle', timeout: 60000 });
  const saved = page.getByRole('list', { name: 'Saved inspection plans' });
  const listMetrics = await saved.evaluate(node => ({ height: node.clientHeight, scroll: node.scrollHeight, width: node.clientWidth, scrollbar: getComputedStyle(node).scrollbarWidth, overscroll: getComputedStyle(node).overscrollBehaviorY }));
  assert.ok(listMetrics.height > 350, JSON.stringify(listMetrics));
  assert.ok(listMetrics.scroll > listMetrics.height);
  assert.equal(listMetrics.scrollbar, 'thin');
  assert.equal(listMetrics.overscroll, 'contain');
  const screenshot = name => page.screenshot({ path: join(shots, name), animations: 'disabled' });
  await screenshot('sidebar-1440.png');
  await saved.getByRole('button').last().click();
  const menu = page.getByRole('menu');
  assert.ok(await menu.isVisible());
  assert.equal(await menu.evaluate(node => { const rect = node.getBoundingClientRect(); return node.contains(document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2)); }), true);
  await screenshot('sidebar-menu.png');
  await page.keyboard.press('Escape');
  assert.equal(await menu.count(), 0);
  await page.setViewportSize({ width: 1024, height: 640 });
  assert.ok(await saved.evaluate(node => node.clientHeight > 150));
  await screenshot('sidebar-1024.png');
  await page.setViewportSize({ width: 1440, height: 900 });

  await page.locator('[data-item-id="ITEM-3"] > button').click();
  await page.getByRole('button', { name: 'Edit Tyres & wheel nuts', exact: true }).click();
  const evidence = page.getByRole('combobox', { name: 'Evidence 1 type', exact: true });
  await evidence.click();
  assert.equal(await page.getByRole('option', { name: 'Photo', exact: true }).getAttribute('aria-selected'), 'true');
  const picker = await page.getByRole('listbox').boundingBox(), field = await evidence.boundingBox();
  assert.ok(Math.abs(picker.x - field.x) < 1 && Math.abs(picker.width - field.width) < 1, JSON.stringify({ picker, field }));
  await screenshot('item-picker.png');
  await evidence.press('ArrowDown');
  await evidence.press('Enter');
  assert.equal(await evidence.innerText(), 'Answer');
  assert.equal(await page.getByRole('listbox').count(), 0);
  await evidence.press('Home');
  await evidence.press('Enter');
  assert.equal(await evidence.innerText(), 'Photo');
  await evidence.click();
  await evidence.press('Escape');
  assert.equal(await page.getByRole('listbox').count(), 0);
  assert.equal(await evidence.evaluate(node => node === document.activeElement), true);
  await evidence.press('a');
  await evidence.press('Enter');
  assert.equal(await evidence.innerText(), 'Answer');
  await evidence.press('Home');
  await evidence.press('Enter');
  await evidence.click();
  await evidence.press('Tab');
  assert.equal(await page.getByRole('listbox').count(), 0);
  const component = page.getByRole('combobox', { name: 'Model component', exact: true });
  await component.click();
  await page.getByRole('option', { name: 'Not linked', exact: true }).click();
  await page.getByRole('button', { name: 'Save item', exact: true }).click();
  await page.getByText('No model component linked. Edit to choose one.', { exact: true }).waitFor();
  assert.equal(plan.items.find(item => item.id === 'ITEM-3').comp_id, null);
  assert.equal(plan.items.find(item => item.id === 'ITEM-3').bukti[0].jenis, 'foto');

  const attach = page.getByRole('button', { name: 'Attach a Spec Sheet', exact: true });
  const getStyle = node => ({ background: getComputedStyle(node).backgroundColor, color: getComputedStyle(node).color });
  await page.mouse.move(800, 20);
  const rest = await attach.evaluate(getStyle);
  await attach.hover();
  await page.waitForFunction(({ restColor }) => getComputedStyle(document.querySelector('button[aria-label="Attach a Spec Sheet"]')).backgroundColor !== restColor, { restColor: rest.background });
  assert.notDeepEqual(await attach.evaluate(getStyle), rest);
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.mouse.down();
  await page.waitForFunction(() => getComputedStyle(document.querySelector('button[aria-label="Attach a Spec Sheet"]')).scale === '0.96');
  await page.mouse.move(800, 20);
  await page.mouse.up();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.getByLabel('Attach Spec Sheet', { exact: true }).setInputFiles(upload);
  assert.equal(await attach.getAttribute('data-attached'), 'true');
  await page.getByRole('img', { name: `Preview of ${upload.name}`, exact: true }).waitFor();
  await screenshot('attachment-ready.png');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  const log = page.getByRole('log', { name: 'Conversation with Lumo' });
  await log.getByText('Processing attachment…', { exact: true }).waitFor();
  const thumbnail = log.getByRole('img', { name: `Preview of ${upload.name}`, exact: true });
  await thumbnail.evaluate(node => node.decode());
  assert.ok(await thumbnail.evaluate(node => node.naturalWidth > 0 && node.src.startsWith('blob:')));
  assert.equal(await attach.isDisabled(), true);
  await attach.hover({ force: true });
  await page.mouse.down();
  assert.notEqual(await attach.evaluate(node => getComputedStyle(node).scale), '0.96');
  await page.mouse.up();
  await screenshot('attachment-processing-pin.png');
  await page.getByRole('button', { name: 'Minimise conversation', exact: true }).click();
  await page.getByRole('button', { name: /Reading the attachment/ }).click();
  await page.getByRole('dialog', { name: 'Lumo conversation' }).getByText('Processing attachment…', { exact: true }).waitFor();
  assert.equal(await page.getByRole('dialog').evaluate(node => getComputedStyle(node).animationName), 'planner-fade-in');
  await screenshot('attachment-processing-dock.png');
  await page.getByRole('dialog', { name: 'Lumo conversation' }).getByRole('button', { name: 'Pin conversation', exact: true }).click();
  assert.equal(turns.length, 1);
  turns[0].resolve(false);
  await log.getByText('Reviewed the sheet and saved its supported specifications.', { exact: true }).waitFor();
  await page.waitForFunction(() => !document.querySelector('textarea[aria-label="Message Lumo"]')?.disabled);
  await log.getByText(upload.name, { exact: true }).waitFor();
  await thumbnail.evaluate(node => node.decode());
  assert.ok(await thumbnail.evaluate(node => node.src.includes('/api/files/FILE-UI-POLISH')));
  const urls = await page.evaluate(() => window.previewUrls);
  assert.deepEqual([...urls.created].sort(), [...urls.revoked].sort());
  await screenshot('attachment-sent.png');
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('log').getByText(upload.name, { exact: true }).waitFor();
  await page.getByRole('log').getByRole('img', { name: `Preview of ${upload.name}`, exact: true }).evaluate(node => node.decode());

  await page.getByLabel('Attach Spec Sheet', { exact: true }).setInputFiles({ name: 'Spec Sheet.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7\n') });
  await page.getByText('PDF document', { exact: false }).waitFor();
  await page.getByRole('button', { name: 'Remove attachment', exact: true }).click();
  assert.equal(await attach.getAttribute('data-attached'), 'false');
  await page.getByLabel('Attach Spec Sheet', { exact: true }).setInputFiles(upload);
  await page.getByRole('textbox', { name: 'Message Lumo', exact: true }).fill('Keep this draft if processing fails.');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await log.getByText('Processing attachment…', { exact: true }).waitFor();
  turns[1].resolve(true);
  await page.getByText('The attachment could not be processed. Please try again.', { exact: true }).waitFor();
  await page.getByText('Ready to send', { exact: true }).waitFor();
  assert.equal(await page.getByRole('textbox', { name: 'Message Lumo', exact: true }).inputValue(), 'Keep this draft if processing fails.');
  await page.getByRole('button', { name: 'Remove attachment', exact: true }).click();
  await page.getByRole('textbox', { name: 'Message Lumo', exact: true }).fill('');
  await page.reload({ waitUntil: 'networkidle' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('textbox', { name: 'Message Lumo', exact: true }).click();
  await page.getByRole('dialog', { name: 'Lumo conversation', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Pin conversation', exact: true }).count(), 0);
  await page.getByRole('dialog').getByRole('img', { name: `Preview of ${upload.name}`, exact: true }).evaluate(node => node.decode());
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  assert.equal(overflow, false);
  await screenshot('chat-390.png');
  assert.deepEqual(errors, []);
  const result = { historyScroll: listMetrics, menuNotClipped: true, selectMouseKeyboardAndSave: true, attachmentHoverPressSelectedDisabled: true, fileOnlyPendingPreview: true, dockAndPin: true, savedPreviewAfterReload: true, objectUrlsRevoked: true, pdfAndRemoval: true, retryPreservesDraft: true, noHorizontalOverflow390: true, errors, screenshots: shots };
  await writeFile(join(shots, 'planner-polish-check.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally { await browser.close(); }
