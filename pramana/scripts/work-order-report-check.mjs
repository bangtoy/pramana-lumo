import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const base = `http://localhost:${process.env.PORT || 3002}`;
const reportId = process.env.REPORT_ID || 'LI-ee9abbcb-7a1d-470a-beb0-d716984c73db';
const api = async path => { const r = await fetch(base + path); assert.equal(r.status, 200); return r.json(); };
const before = await api('/api/work-order');
assert.equal(before.filter(w => w.laporan_id === reportId).length, 0, 'Choose a submitted report without work orders.');
const report = await api(`/api/laporan/${reportId}`);
const findings = Object.values(report.hasil).filter(f => f.status === 'tidak_baik');
assert.equal(findings.length, 1);
const itemId = Object.keys(report.hasil).find(id => report.hasil[id].status === 'tidak_baik');
const openBefore = before.filter(w => w.status === 'terbuka').length;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', e => { if (e.type() === 'error') errors.push(e.text()); });
async function snapshot(name) {
  if (await page.locator('.iso').count()) await page.locator('.iso svg').first().waitFor();
  await page.evaluate(async () => { await document.fonts.ready; await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))); });
  await page.screenshot({ path: `../docs/verification/screenshots/${name}.png`, animations: 'disabled' });
}
const badgeCount = count => page.waitForFunction(expected => document.querySelector('nav[aria-label="Dashboard pages"] a[href="/supervisor/work-order"] .t-label')?.textContent === String(expected), count);
try {
  await page.goto(`${base}/supervisor/laporan`, { waitUntil: 'networkidle' });
  const reportRow = page.locator(`[data-report="${reportId}"]`);
  await reportRow.getByRole('link', { name: 'Not created', exact: true }).click();
  await page.getByRole('button', { name: 'Create work orders (1 finding)', exact: true }).waitFor();
  await snapshot('report-create-work-order-1440');
  const started = Date.now();
  const responsePromise = page.waitForResponse(r => r.url().endsWith('/api/work-order') && r.request().method() === 'POST', { timeout: 45000 });
  await page.getByRole('button', { name: 'Create work orders (1 finding)', exact: true }).click();
  const response = await responsePromise; assert.equal(response.status(), 201);
  const created = await response.json(); assert.equal(created.length, 1);
  const order = created[0], creationMs = Date.now() - started;
  assert.equal(order.item_id, itemId); assert.equal(order.prioritas, 'tinggi'); assert.ok(order.judul && order.tindakan);
  await page.waitForURL(url => url.pathname === '/supervisor/work-order' && url.searchParams.get('laporan') === reportId);
  const workRow = page.locator(`[data-work-order="${order.id}"]`);
  await workRow.waitFor(); assert.equal(await page.locator('[data-work-order]').count(), 1);
  await badgeCount(openBefore + 1);
  await workRow.getByRole('textbox', { name: /^Mechanic/ }).fill('Sinta');
  const assigned = page.waitForResponse(r => r.url().endsWith(`/api/work-order/${order.id}`) && r.request().method() === 'PATCH');
  await workRow.getByRole('textbox', { name: /^Mechanic/ }).press('Tab'); await assigned;
  await workRow.getByRole('link', { name: reportId, exact: true }).click();
  const finding = page.locator(`#finding-${itemId}`), card = finding.getByRole('link', { name: `Work order: ${order.judul}`, exact: true });
  await card.getByText('Assigned to Sinta', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Work orders created', exact: true }).isDisabled(), true);
  await card.click();
  await page.waitForURL(url => url.searchParams.get('wo') === order.id);
  assert.equal(await workRow.evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(239, 248, 255)');
  await workRow.getByRole('button', { name: 'Mark complete' }).click();
  await page.getByRole('textbox', { name: 'Completion note (optional)' }).fill('Damaged tyre replaced and wheel fasteners checked.');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await workRow.getByText('Completed', { exact: true }).waitFor();
  await badgeCount(openBefore);
  await workRow.getByRole('link', { name: reportId, exact: true }).click();
  await finding.getByText('Handled', { exact: true }).waitFor();
  await card.getByText('Completed', { exact: true }).waitFor();
  await page.waitForFunction(selector => getComputedStyle(document.querySelector(selector)).color === 'rgb(23, 166, 115)', `#finding-${itemId} a[href*="?wo="] span > span:last-child`);
  const completedReport = await api(`/api/laporan/${reportId}`); assert.equal(completedReport.hasil[itemId].ditangani, true); assert.equal(completedReport.hasil[itemId].stop, true);
  await snapshot('report-work-order-completed-1440');
  await card.scrollIntoViewIfNeeded();
  await snapshot('report-work-order-card-1440');
  await finding.getByRole('button', { name: 'Mark unresolved', exact: true }).click();
  await card.getByText('Assigned to Sinta', { exact: true }).waitFor(); await badgeCount(openBefore + 1);
  const reopened = await api(`/api/work-order/${order.id}`); assert.equal(reopened.status, 'terbuka'); assert.equal(reopened.catatan_selesai, null);
  await finding.getByRole('button', { name: 'Mark handled', exact: true }).click();
  await card.getByText('Completed', { exact: true }).waitFor(); await badgeCount(openBefore);
  assert.equal((await api(`/api/work-order/${order.id}`)).catatan_selesai, 'Marked handled from the inspection report.');
  await page.getByRole('link', { name: 'Inspection reports', exact: true }).last().click();
  await reportRow.getByText('Completed', { exact: true }).waitFor();
  await snapshot('reports-work-order-1440');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${base}/supervisor/laporan/${reportId}`, { waitUntil: 'networkidle' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(await page.locator('#supervisor-content').evaluate(el => el.scrollWidth <= el.clientWidth), true);
  await snapshot('report-work-order-390');
  await page.goto(`${base}/petugas/riwayat/${reportId}`, { waitUntil: 'networkidle' });
  assert.equal(await page.getByRole('button', { name: /Create work orders|Work orders created|Mark handled|Mark unresolved/ }).count(), 0);
  assert.equal(await page.getByRole('link', { name: /^Work order:/ }).count(), 0);
  assert.deepEqual(errors, []);
  const result = { reportId, orderId: order.id, title: order.judul, creationMs, onlyNotGoodFindings: true, scopedRedirect: true, linkedHighlight: true, assignedMechanicCard: true, completionSynchronized: true, reportReopenSynchronized: true, sidebarUpdates: true, reportListCompleted: true, inspectorReadOnly: true, responsive: true, errors };
  writeFileSync('../docs/verification/work-order-report-check.json', JSON.stringify(result, null, 2)); console.log(result);
} finally { await browser.close(); }
