import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";

test("SQLite seeds once, persists validated documents, and recovers interrupted jobs",async()=>{
  process.env.DATA_DIR=mkdtempSync(join(tmpdir(),"pramana-db-"));
  const db=await import("../lib/db.ts");
  const plan=db.getRencana("RI-DT-UTYPE-01")!;
  assert.equal(plan.items.length,8);
  assert.equal(db.listRencana().length,1);
  assert.equal(db.listReusableModels().length,2);
  assert.equal(Object.values(db.getLaporan("LI-2026-10-29-DT07")!.hasil).filter(h=>h.stop).length,2);
  assert.equal(db.database().prepare("PRAGMA journal_mode").get()!.journal_mode,"wal");
  assert.equal(db.database().prepare("PRAGMA busy_timeout").get()!.timeout,5000);
  const message={id:"MSG-1",role:"user" as const,text:"Updated plan",created_at:db.now()};
  db.saveRencanaChat(plan.id,[message],[{role:"user",content:"Updated plan"}]);
  db.saveRencana({...plan,judul:"Changed manually"});
  assert.equal(db.getRencana(plan.id)!.judul,"Changed manually");
  assert.equal(db.getRencanaChat(plan.id).messages[0].id,message.id);
  assert.notEqual(db.getLaporan("LI-2026-10-29-DT07")!.rencana_snapshot!.judul,"Changed manually");
  assert.throws(()=>db.saveRencana({...plan,items:[{...plan.items[0],urutan:"invalid" as unknown as number}]}));
  db.insertFile({id:"FILE-TEST",name:"test.jpg",ref:"data:uploads/test.jpg",mime:"image/jpeg",caption:null,created_at:db.now()});
  db.setFileCaption("FILE-TEST","A clear photo");
  assert.equal(db.getFile("FILE-TEST")!.caption,"A clear photo");
  db.saveModel({...db.getModel("MDL-DT-UTYPE")!,id:"JOB-TEST",status:"proses",sumber:"generate"});
  const child=spawnSync(process.execPath,["--experimental-strip-types","--input-type=module","-e",`import {listRencana,getModel,getRencanaChat} from './lib/db.ts'; console.log(JSON.stringify({plans:listRencana().length,status:getModel('JOB-TEST').status,messages:getRencanaChat('${plan.id}').messages.length}));`],{encoding:"utf8",env:process.env});
  assert.equal(child.status,0,child.stderr);
  assert.deepEqual(JSON.parse(child.stdout.trim()),{plans:1,status:"gagal",messages:1});
  assert.equal(db.listModels().length,3);
  assert.equal(db.listLaporan("terkirim").length,1);
  const temporary={...plan,id:db.newId("RI")};
  db.saveRencana(temporary);db.deleteRencana(temporary.id);
  assert.equal(db.getRencana(temporary.id),null);
  const {resolveRef}=await import("../lib/paths.ts");
  assert.throws(()=>resolveRef("data:../outside"));
  assert.throws(()=>resolveRef("public:/outside"));
  assert.throws(()=>resolveRef("https:example.com"));
});
