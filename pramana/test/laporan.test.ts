import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
process.env.DATA_DIR = mkdtempSync(path.join(tmpdir(), 'pramana-report-'));
const { createReport, setHeader, recordItem, submitReport, requireReport, publicReport } = await import('../lib/laporan.ts');
const { getRencana, saveRencana, saveLaporan } = await import('../lib/db.ts');
const { progress, nextItem, verdict, counts } = await import('../lib/rules.ts');
test('inspection snapshot, mandatory evidence, completeness, provenance and STOP remain authoritative', () => {
  const draft = createReport();
  setHeader(draft.id, { petugas: 'Alex', lokasi: 'Tanjung Enim', rencana_id: 'RI-DT-UTYPE-01', unit: 'DT-09 · B 9129 KD' });
  const plan = getRencana('RI-DT-UTYPE-01')!;
  saveRencana({ ...plan, items: [] });
  assert.equal(requireReport(draft.id).rencana_snapshot?.items.length, 8);
  assert.throws(() => submitReport(draft.id), /Complete every inspection item/);
  const finding = { item_id: 'ITEM-1', status: 'baik' as const, stop: false, catatan: 'Inspected safely.', bukti_ids: [], alasan: null };
  assert.throws(() => recordItem(draft.id, finding), /attach 1 clear photo/);
  assert.throws(() => recordItem(draft.id, { ...finding, bukti_ids: ['FILE-APAR-LABEL'] }), /attached to this inspection/);
  const report = requireReport(draft.id);
  report.messages.push({ id: 'evidence', role: 'user', text: 'Photo', files: [{ id: 'FILE-APAR-LABEL' }], created_at: new Date().toISOString() }); saveLaporan(report);
  assert.throws(() => recordItem(draft.id, { ...finding, bukti_ids: ['FILE-APAR-LABEL'], status: 'tidak_bisa_diperiksa' }), /Explain why/);
  assert.throws(() => recordItem(draft.id, { ...finding, bukti_ids: ['FILE-APAR-LABEL'], stop: true }), /cannot also be marked STOP/);
  for (const item of plan.items) recordItem(draft.id, { ...finding, item_id: item.id, bukti_ids: ['FILE-APAR-LABEL'], status: item.id === 'ITEM-3' ? 'tidak_baik' : 'baik', stop: item.id === 'ITEM-3' });
  assert.equal(progress(requireReport(draft.id)).percent, 100); assert.equal(nextItem(requireReport(draft.id)), null);
  submitReport(draft.id); const saved = requireReport(draft.id);
  assert.equal(saved.status, 'terkirim'); assert.equal(counts(saved).stop, 1); assert.equal(verdict(saved), 'DT-09 is not roadworthy');
  assert.ok(!('agent_history' in publicReport(saved)));
  assert.throws(() => recordItem(draft.id, finding), /already|submitted/);
  assert.throws(() => setHeader(draft.id, { petugas: 'Changed', lokasi: null, unit: null, rencana_id: null }), /submitted/);
});
